// Optional browser QA; Playwright is a separate tool, not an app dependency.
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE_PATH ? pathToFileURL(process.env.PLAYWRIGHT_MODULE_PATH).href : 'playwright');
const base = process.env.BROWSE_TEST_URL || 'http://127.0.0.1:5180';
const artifacts = 'node_modules/.browse-verification';
await mkdir(artifacts, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const titles = () => page.locator('[data-listing-title]').allTextContents();
const ready = () => page.waitForFunction(() => /\d+ listings?/.test(document.querySelector('[data-browse-count]')?.textContent || ''));
const submit = async (term) => { await page.getByLabel('Search by title').fill(term); await page.getByRole('button', { name: 'Search', exact: true }).click(); };
const requests = [];
page.on('request', request => { if (/\/rest\/v1\/(listings|categories)\?/.test(request.url())) requests.push(request.url()); });
try {
  const responsePromise = page.waitForResponse(response => response.url().includes('/rest/v1/listings?'));
  await page.goto(`${base}/listings`);
  const response = await responsePromise;
  const live = await response.json();
  await ready();
  assert.ok(live.length >= 18);
  assert.ok(new Set(live.map(row => row.owner_id)).size >= 3, 'Public page includes all owners');
  assert.ok(live.every(row => row.category?.name));
  assert.deepEqual(await titles(), live.map(row => row.title));
  assert.equal(await page.title(), 'Browse Listings | MiniMarket');
  assert.equal(await page.locator('[data-view-details]:visible').count(), live.length);
  assert.equal(await page.locator('[data-listing-description]:visible').count(), live.length);
  assert.ok((await page.locator('[data-listing-price]').first().textContent()).startsWith('€'));
  assert.equal(await page.locator('#browse-category option').count(), 7);
  const baseline = requests.length;
  await page.evaluate(() => { window.browseMarker = true; });
  await submit('  LAPTOP  ');
  assert.equal(new URL(page.url()).searchParams.get('search'), 'LAPTOP');
  const laptops = live.filter(row => /laptop/i.test(row.title));
  assert.deepEqual(await titles(), laptops.map(row => row.title));
  const electronics = live.find(row => row.category.name === 'Electronics').category_id;
  await page.getByLabel('Category', { exact: true }).selectOption(electronics);
  assert.deepEqual(await titles(), laptops.filter(row => row.category_id === electronics).map(row => row.title));
  await page.getByLabel('Sort by').selectOption('price-asc');
  assert.equal(new URL(page.url()).searchParams.get('sort'), 'price-asc');
  await submit('');
  const electronicRows = live.filter(row => row.category_id === electronics);
  assert.deepEqual(await titles(), [...electronicRows].sort((a,b) => a.price-b.price).map(row => row.title));
  await page.getByLabel('Sort by').selectOption('price-desc');
  assert.deepEqual(await titles(), [...electronicRows].sort((a,b) => b.price-a.price).map(row => row.title));
  await page.goBack();
  assert.equal(await page.getByLabel('Sort by').inputValue(), 'price-asc');
  await page.goBack();
  assert.equal(await page.getByLabel('Search by title').inputValue(), 'LAPTOP');
  await page.goForward();
  assert.equal(await page.getByLabel('Search by title').inputValue(), '');
  assert.equal(await page.evaluate(() => window.browseMarker), true);
  assert.equal(requests.length, baseline, 'Filters, sorting, and history do not refetch');
  await page.locator('[data-view-details]').first().click();
  await page.locator('#view-listing-modal [data-details-content]:not([hidden])').waitFor();
  await page.goBack();
  assert.equal(await page.locator('#view-listing-modal').isVisible(), false, 'Query history closes the old View modal');
  assert.equal(await page.locator('.modal-backdrop').count(), 0);
  await page.goForward();
  await page.getByRole('button', { name: 'Clear filters' }).click();
  assert.deepEqual(await titles(), live.map(row => row.title));
  await submit('no-such-product-19028');
  assert.equal(await page.locator('.listing-card').count(), 0);
  assert.match(await page.locator('[data-browse-feedback]').textContent(), /No listings match/);
  await page.getByRole('button', { name: 'Clear filters' }).click();
  const details = await page.locator('[data-listing-link]').first().getAttribute('href');
  await page.locator('[data-view-details]').first().click();
  await page.locator('#view-listing-modal [data-details-content]:not([hidden])').waitFor();
  assert.equal(new URL(page.url()).pathname, '/listings');
  await page.getByRole('link', { name: 'Open details page' }).click();
  assert.equal(new URL(page.url()).pathname, details);
  assert.equal(await page.locator('h1').textContent(), 'Listing Details');
  await page.goBack(); await ready();
  for (const [width, columns] of [[1440,4], [1024,3], [768,2], [375,1], [320,1]]) {
    await page.setViewportSize({ width, height: 900 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    const positions = await page.locator('[data-browse-grid] > .col').evaluateAll(nodes => nodes.map(node => Math.round(node.getBoundingClientRect().top)));
    assert.equal(positions.filter(top => top === positions[0]).length, columns);
    if ([1440,375].includes(width)) await page.screenshot({ path: `${artifacts}/${width}.png`, fullPage: true });
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${base}/listings?search=laptop&category=electronics&sort=price-asc`); await ready();
  assert.deepEqual(await titles(), laptops.filter(row => row.category_id === electronics).map(row => row.title));
  await page.reload(); await ready();
  assert.equal(await page.getByLabel('Sort by').inputValue(), 'price-asc');
  assert.equal(await page.getByLabel('Category', { exact: true }).inputValue(), electronics);
  await page.goto(`${base}/listings?category=unknown-category`); await ready();
  assert.equal(await page.locator('.listing-card').count(), 0);
  await page.goto(`${base}/listings?q=laptop`); await ready();
  assert.deepEqual(await titles(), laptops.map(row => row.title));
  await page.goto(base);
  await page.locator('.home-category').first().waitFor();
  const categoryHref = await page.locator('.home-category').first().getAttribute('href');
  await page.locator('.home-category').first().click(); await ready();
  assert.equal(await page.getByLabel('Category', { exact: true }).inputValue(), new URL(categoryHref,base).searchParams.get('category'));
  await page.goto(base);
  await page.getByLabel('Search advertisements', { exact:true }).fill('laptop');
  await page.locator('[data-home-search] button').click(); await ready();
  assert.deepEqual(await titles(), laptops.map(row => row.title));
  console.log('PASS: live public listings/category join, search, combined filters, both price sorts, Home links, details navigation, URL/refresh/history, no filter refetch, and 4/3/2/1-column layouts.');

  let mode = 'loading';
  let release;
  const gate = new Promise(resolve => { release = resolve; });
  await page.route('**/rest/v1/listings?*', async route => {
    if (mode === 'loading') await gate;
    if (mode === 'error') return route.fulfill({ status: 503, contentType:'application/json', body: JSON.stringify({ message:'internal-sensitive-database-error' }) });
    const rows = mode === 'empty' ? [] : [{ ...live[0], title:'<img src=x onerror=alert(1)>'.repeat(12), description:'<script>alert(1)</script>'.repeat(40), image_url:'javascript:alert(1)' }];
    await route.fulfill({ status:200, contentType:'application/json', body:JSON.stringify(rows) });
  });
  await page.goto(`${base}/listings`);
  await page.getByText('Loading marketplace listings…', { exact:true }).waitFor();
  assert.equal(await page.locator('[data-browse-grid]').getAttribute('aria-busy'), 'true');
  mode = 'empty'; release(); await ready();
  assert.match(await page.locator('[data-browse-feedback]').textContent(), /No listings yet/);
  mode = 'error'; await page.reload();
  await page.getByRole('button', { name:'Try again' }).waitFor();
  assert.equal((await page.locator('main').textContent()).includes('internal-sensitive'), false);
  const categoriesBeforeRetry = requests.filter(url => url.includes('/categories?')).length;
  mode = 'safe'; await page.getByRole('button', { name:'Try again' }).click(); await ready();
  assert.equal(requests.filter(url => url.includes('/categories?')).length, categoriesBeforeRetry, 'Retry retains successful category request');
  assert.equal(await page.locator('[data-listing-title] img, [data-listing-description] script').count(), 0);
  assert.ok((await page.locator('[data-listing-description]').textContent()).length <= 160);
  assert.equal(await page.locator('[data-listing-image]').first().isVisible(), false);
  // A response after unmount must not touch the next page or show an error toast.
  await page.unroute('**/rest/v1/listings?*');
  let releaseLate;
  const late = new Promise(resolve => { releaseLate = resolve; });
  await page.route('**/rest/v1/listings?*', async route => { await late; await route.fulfill({ status:503, contentType:'application/json', body:'{}' }); });
  await page.reload();
  await page.getByText('Loading marketplace listings…', { exact:true }).waitFor();
  await page.locator('header').getByRole('link', { name:'Login', exact:true }).click();
  releaseLate();
  await page.waitForTimeout(300);
  assert.equal(await page.locator('h1').textContent(), 'Login');
  assert.equal(await page.locator('.toast.show').count(), 0);
  await page.unroute('**/rest/v1/listings?*');
  await page.getByLabel('Email', { exact:true }).fill('test@test.com');
  await page.getByLabel('Password', { exact:true }).fill('pass123');
  await page.getByRole('button', { name:'Login', exact:true }).click();
  await page.waitForURL(url => url.pathname === '/dashboard');
  await page.locator('header').getByRole('link', { name:'Browse Listings', exact:true }).click(); await ready();
  assert.deepEqual(await titles(), live.map(row => row.title), 'Signed-in users still see all public owners');
  // Regress the router leave guard without submitting or changing any database record.
  await page.locator('header').getByRole('link', { name:'Add Listing', exact:true }).click();
  await page.locator('[data-listing-form] [data-listing-fields]:not([disabled])').waitFor();
  await page.locator('#listing-title').fill('Unsaved browser verification');
  page.once('dialog', dialog => dialog.dismiss());
  await page.locator('header').getByRole('link', { name:'Browse Listings', exact:true }).click();
  assert.equal(new URL(page.url()).pathname, '/listings/add');
  page.once('dialog', dialog => dialog.accept());
  await page.goBack(); await ready();
  assert.equal(new URL(page.url()).pathname, '/listings');
  await page.getByRole('button', { name:'Logout', exact:true }).click();
  await page.waitForURL(url => url.pathname === '/');
  assert.deepEqual(errors, []);
  console.log('PASS: controlled loading, empty, error/retry, cached successful reads, safe text/images, unmount cleanup, signed-in browsing, and router dirty-form guard. No database records modified.');
} finally { await browser.close(); }
