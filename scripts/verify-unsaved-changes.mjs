import assert from 'node:assert/strict';
import { createUnsavedChangesGuard } from '../src/utils/unsaved-changes.js';

globalThis.window = new EventTarget();
let allow = false;
let confirmations = 0;
window.confirm = () => { confirmations += 1; return allow; };
const form = new EventTarget();
let values = { title: 'Original', price: '10', category_id: 'category', description: '' };
const guard = createUnsavedChangesGuard(form, () => values);
assert.equal(guard.canLeave(), true);
assert.equal(confirmations, 0, 'Pristine forms do not ask');
values.title = 'Changed'; form.dispatchEvent(new Event('input'));
assert.equal(guard.isDirty(), true);
assert.equal(guard.canLeave(), false);
allow = true; assert.equal(guard.canLeave(), true);
const unload = new Event('beforeunload', { cancelable: true });
window.dispatchEvent(unload); assert.equal(unload.defaultPrevented, true);
values.title = 'Original'; form.dispatchEvent(new Event('change'));
assert.equal(guard.isDirty(), false);
const pristineUnload = new Event('beforeunload', { cancelable: true });
window.dispatchEvent(pristineUnload); assert.equal(pristineUnload.defaultPrevented, false);
values.description = 'New description'; form.dispatchEvent(new Event('input'));
guard.markClean(); assert.equal(guard.isDirty(), false);
values.price = '12'; form.dispatchEvent(new Event('input'));
guard.dispose();
const disposedUnload = new Event('beforeunload', { cancelable: true });
window.dispatchEvent(disposedUnload); assert.equal(disposedUnload.defaultPrevented, false);
delete globalThis.window;
console.log('PASS: dirty tracking, unchanged/reverted forms, leave confirmation, refresh warning, saved state, and listener cleanup.');
